"""Generate offline readings and word meanings for every sentence in all languages.

Uses the translation cache and converters from build-multilingual.py. Run that
builder first. Original Thai glossary definitions take precedence over machine
translations. Full sentence translations remain the context reference.
"""
import concurrent.futures
import importlib.util
import json
import re
import subprocess
import time
import sys

import requests

spec = importlib.util.spec_from_file_location('multilingual', __file__.replace('build-token-data.py', 'build-multilingual.py'))
m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)
ROOT = m.ROOT
OFFLINE = '--cached-only' in sys.argv
THAI_CORRECTIONS = {
    'ก็ตาม': 'gɔ̂ɔ dtaam', 'จานนี้ก็อร่อย': 'jaan níi gɔ̂ɔ à-rɔ̀i', 'นี่ก็อร่อยดี': 'nîi gɔ̂ɔ à-rɔ̀i dii',
    'ภาวะ': 'phaa-wá', 'วิเคราะห์': 'wí-khrɔ́', 'สต็': 'sà-dtók (part of สต็อก)',
    'อบอุ่น': 'òp-ùn', 'อายุ': 'aa-yú', 'แออัด': 'ɛɛ-àt', 'ไฟฟ้า': 'fai-fáa',
    'การปรุงอาหาร': 'gaan bprung aa-hǎan', 'ความแออัด': 'khwaam ɛɛ-àt',
    'ความไว้วางใจ': 'khwaam wái-waang-jai', 'เครื่องใช้ไฟฟ้า': 'khrʉ̂ʉang chái fai-fáa',
    'ภาวะแทรกซ้อน': 'phaa-wá sɛ̂ɛk-sɔ́ɔn', 'การต่ออายุ': 'gaan dtɔ̀ɔ aa-yú',
    'ความอบอุ่น': 'khwaam òp-ùn', 'มลพิษทางอากาศ': 'mon-lá-phít thaang aa-gàat',
    'ขออภัยในความไม่สะดวก': 'khɔ̌ɔ à-phai nai khwaam mâi sà-dùuak',
    'ขึ้นอยู่กับ': 'khʉ̂n yùu gàp', 'ต่ออายุ': 'dtɔ̀ɔ aa-yú', 'ถึงแม้ว่า': 'thʉ̌ng mɛ́ɛ wâa',
    'ถ้า...ก็...': 'thâa ... gɔ̂ɔ ...', 'มีอะไรให้ช่วยก็บอก': 'mii à-rai hâi chûuai gɔ̂ɔ bɔ̀ɔk',
    'ยกตัวอย่าง': 'yók dtuua-yàang', 'ลายลักษณ์อักษร': 'laai-lák àk-sɔ̌ɔn',
    'หมดสต็อก': 'mòt sà-dtók', 'อย่างไรก็ตาม': 'yàang-rai gɔ̂ɔ dtaam',
    'แก้ไขปัญหา': 'gɛ̂ɛ-khǎi bpan-hǎa', 'ๆ': 'repeat preceding word'
}


def thai_reading(text, supplied):
    """Apply reviewed Thai repairs before cache/network/RTGS fallbacks; never return Thai script as romanization."""
    if text in THAI_CORRECTIONS:
        return THAI_CORRECTIONS[text]
    if supplied and not re.search(r'[\u0e00-\u0e7f]', supplied):
        return supplied
    if text == 'ๆ':
        return 'repeat preceding word'
    cache_key = json.dumps(['reading', 'th', text], ensure_ascii=False)
    if cache_key in m.cache:
        return m.cache[cache_key]
    if OFFLINE:
        from pythainlp.transliterate import romanize
        value = romanize(text, engine='royin')
        if not value or re.search(r'[\u0e00-\u0e7f]', value):
            print(f'Thai reading needs correction: {text}: {value}', flush=True)
            return ''
        return value
    for attempt in range(4):
        try:
            response = requests.get('https://translate.googleapis.com/translate_a/single',
                                    params={'client': 'gtx', 'sl': 'th', 'tl': 'en', 'dt': ['t', 'rm'], 'q': text}, timeout=25)
            response.raise_for_status()
            value = next((part[3] for part in response.json()[0] if len(part) > 3 and part[3]), '')
            if not value or re.search(r'[\u0e00-\u0e7f]', value):
                raise ValueError('Missing romanization')
            with m.lock:
                m.cache[cache_key] = value
            return value
        except Exception:
            if attempt == 3:
                raise
            time.sleep(attempt + 1)


def main():
    """Collect actual runtime words, then rebuild offline meanings and reading tables without audio files."""
    # JavaScript owns segmentation and the runtime load order; Python owns translations.
    response = subprocess.run([m.NODE, str(ROOT / 'scripts' / 'collect-token-data.cjs')],
                              cwd=ROOT, capture_output=True, text=True, encoding='utf-8', check=True)
    data = json.loads(response.stdout)
    print(json.dumps({'words': {code: len(words) for code, words in data['words'].items()}}), flush=True)
    for word, meaning in data['gloss'].items():
        m.cache[m.key(word, 'th', 'en')] = meaning
    english_words = set(data['words']['en'])
    tokens = {}
    for code, words in data['words'].items():
        if code != 'en' and not OFFLINE:
            m.translate_all(words, code, 'en')
        tokens[code] = {word: m.translated(word, code, 'en') for word in words}
        english_words.update(tokens[code].values())
    for code in m.LANGUAGES:
        if code != 'en' and not OFFLINE:
            m.translate_all(sorted(english_words), 'en', code)
    meanings = {word: {code: value for code in m.LANGUAGES
                      if (value := word if code == 'en' else m.cache.get(m.key(word, 'en', code)))}
                for word in sorted(english_words)}
    (ROOT / 'dist' / 'data-token-meanings.js').write_text(
        '// Generated by python scripts/build-token-data.py. See DEVELOPER.md before rebuilding.\n// Offline token definitions; machine translations are approximate and context-dependent.\nwindow.TOKEN_ENGLISH = '
        + json.dumps(tokens, ensure_ascii=False, separators=(',', ':')) + ';\nwindow.TOKEN_MEANINGS = '
        + json.dumps(meanings, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
    readings = {}
    for code, words in data['words'].items():
        if code == 'th':
            wanted = sorted(set(words) | set(data['readings']) | set(data['texts']['th']))
            with concurrent.futures.ThreadPoolExecutor(max_workers=6) as executor:
                values = list(executor.map(lambda word: thai_reading(word, data['readings'].get(word, '')), wanted))
            readings[code] = dict(zip(wanted, values))
        elif code in ['zh', 'ja', 'ko']:
            readings[code] = {word: m.reading(word, code) for word in sorted(set(words) | set(data['texts'][code]))}
    m.save_cache()
    (ROOT / 'dist' / 'data-token-readings.js').write_text(
        '// Generated by python scripts/build-token-data.py. See DEVELOPER.md before rebuilding.\n// Word and sentence reading hints. Pinyin, Hepburn, Korean romanization; Thai hints are approximate.\nwindow.TOKEN_READINGS = '
        + json.dumps(readings, ensure_ascii=False, separators=(',', ':'))
        + ';\nObject.assign(window.THAI_READINGS, window.TOKEN_READINGS.th);\n', encoding='utf-8')
    print(json.dumps({'definitions': len(meanings), 'readings': {code: len(words) for code, words in readings.items()}}), flush=True)


if __name__ == '__main__':
    main()
