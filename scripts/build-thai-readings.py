"""Build static pronunciation hints for every Thai breakdown word.

Run after downloading the Kaikki Thai JSONL dictionary to
``.thai-dictionary.jsonl`` in the project root. The dictionary is adapted
from Wiktionary under CC BY-SA 4.0; see README.md.
"""

import json
import os
import re
import shutil
import subprocess
from pathlib import Path

from pythainlp.transliterate import romanize


ROOT = Path(__file__).resolve().parents[1]
NODE = os.environ.get("NODE_BINARY") or shutil.which("node") or ("C:/nodejs/node.exe" if os.name == "nt" else "node")
DICTIONARY = ROOT / ".thai-dictionary.jsonl"


def load_cards():
    """Read shared authoring inputs without loading the browser controller."""
    result = subprocess.run([NODE, str(ROOT / 'scripts' / 'load-data.cjs'), '--seed'],
                            cwd=ROOT, check=True, capture_output=True, text=True, encoding="utf-8")
    data = json.loads(result.stdout)
    thai = [card for card in data['cards'] if card['lang'] == 'th']
    manual = [line.split('=')[0].split('|')[0].strip()
              for card in thai for field in ['breakdown', 'exampleBreakdown']
              for line in re.split(r'[;\n]+', card.get(field, '')) if line.strip()]
    return {'gloss': list(data['gloss']), 'readings': data['readings'],
            'words': [card['term'] for card in thai if card['kind'] == 'word'], 'manual': manual}


def main():
    """Prefer reviewed/dictionary romanization, use RTGS only when absent, then write reading hints."""
    if not DICTIONARY.exists():
        raise SystemExit(f"Download https://kaikki.org/dictionary/Thai/kaikki.org-dictionary-Thai.jsonl to {DICTIONARY}")
    data = load_cards()
    wanted = set(data["gloss"]) | set(data["words"]) | set(data["manual"])
    from_dictionary = {}
    with DICTIONARY.open(encoding="utf-8") as source:
        for line in source:
            entry = json.loads(line)
            word = entry.get("word")
            if word not in wanted or word in from_dictionary:
                continue
            for sound in entry.get("sounds", []):
                if "Paiboon" in sound.get("raw_tags", []) and sound.get("roman"):
                    from_dictionary[word] = sound["roman"]
                    break
            if word not in from_dictionary:
                for form in entry.get("forms", []):
                    if "romanization" in form.get("tags", []) and form.get("form"):
                        from_dictionary[word] = form["form"]
                        break

    readings = {}
    fallback = 0
    for word in sorted(wanted):
        value = data["readings"].get(word) or from_dictionary.get(word)
        if not value:
            value = romanize(word, engine="royin")
            fallback += 1
        readings[word] = value or word
    output = ROOT / "dist" / "data-th-readings.js"
    output.write_text(
        "// Generated by python scripts/build-thai-readings.py. See DEVELOPER.md before rebuilding.\n"
        "// Thai reading hints for every built-in breakdown word and vocabulary term.\n"
        "// Paiboon forms adapted from Wiktionary/Kaikki (CC BY-SA 4.0); RTGS fallback.\n"
        "window.THAI_READINGS = Object.assign(window.THAI_READINGS || {}, "
        + json.dumps(readings, ensure_ascii=False, separators=(",", ":")) + ");\n",
        encoding="utf-8",
    )
    print(json.dumps({"readings": len(readings), "dictionary": len(readings) - fallback,
                      "rtgs_fallback": fallback, "bytes": output.stat().st_size}))


if __name__ == "__main__":
    main()
